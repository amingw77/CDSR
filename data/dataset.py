"""
NYU Depth v2 dataset loader for guided depth super-resolution.
LR depth generated by bicubic downsampling of HR depth.
RGB guide can be either raw RGB or a Sobel edge map.
"""
import os
import sys
import random

import numpy as np
import torch
import torch.nn.functional as F
from torch.utils.data import Dataset
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from utils.edge_extraction import compute_sobel_numpy


class NYUDepthSR(Dataset):
    """NYU v2 labeled dataset for 8x depth super-resolution.

    Each sample: (lr_depth, rgb_edge, hr_depth, dmin, dmax)
    - lr_depth: bicubic-downsampled depth (1, H/8, W/8), normalized [0,1]
    - rgb_edge: Sobel edge map 3-channel (3, H, W) or raw RGB
    - hr_depth: depth (1, H, W), normalized [0,1] per-sample
    - dmin/max: depth_min*100, depth_max*100 for de-normalization (A2GS style)
    """

    def __init__(self, root: str, scale: int = 8, train: bool = True,
                 train_split: int = 1000, crop_size: int = 224,
                 augment: bool = True, pre_extract_edge: bool = False,
                 repeat: int = 32):
        """
        Args:
            root: path to nyu_labeled directory (contains Depth/ and RGB/)
            scale: super-resolution factor
            train: True for training set, False for test
            train_split: number of training samples (first N indices)
            crop_size: HR crop size, should be divisible by scale and patch size.
            augment: apply random flip/rotation
            pre_extract_edge: return Sobel edge map instead of raw RGB
            repeat: repeat factor for training (each image sampled repeat times
                    with different random crops/augmentations, same as A2GS)
        """
        self.root = root
        self.scale = scale
        self.train = train
        self.crop_size = crop_size
        self.augment = augment and train
        self.pre_extract_edge = pre_extract_edge
        self.repeat = repeat if train else 1

        self.rgb_dir = os.path.join(root, "RGB")
        self.depth_dir = os.path.join(root, "Depth")

        rgb_files = sorted(os.listdir(self.rgb_dir))
        depth_files = sorted(os.listdir(self.depth_dir))

        # Match pairs by index
        self.samples = []
        for rf in rgb_files:
            idx = os.path.splitext(rf)[0]
            npy_name = idx + ".npy"
            if npy_name in depth_files:
                self.samples.append((os.path.join(self.rgb_dir, rf),
                                     os.path.join(self.depth_dir, npy_name)))

        if train:
            self.samples = self.samples[:train_split]
        else:
            self.samples = self.samples[train_split:]

    def __len__(self):
        return len(self.samples) * self.repeat

    def _augment(self, rgb: np.ndarray, depth: np.ndarray) -> tuple:
        """Apply random flip and 90-degree rotation."""
        if random.random() < 0.5:
            rgb = np.fliplr(rgb).copy()
            depth = np.fliplr(depth).copy()
        if random.random() < 0.5:
            rgb = np.flipud(rgb).copy()
            depth = np.flipud(depth).copy()
        if random.random() < 0.5:
            k = random.randint(1, 3)
            rgb = np.rot90(rgb, k=k).copy()
            depth = np.rot90(depth, k=k).copy()
        return rgb, depth

    def __getitem__(self, idx: int):
        if self.train:
            idx = idx % len(self.samples)  # cyclic repeat with different crops
        rgb_path, depth_path = self.samples[idx]

        # Load RGB and depth
        rgb = Image.open(rgb_path).convert("RGB")
        rgb = np.array(rgb)  # uint8 HWC

        depth = np.load(depth_path).astype(np.float32)
        h, w = depth.shape

        if self.train and self.crop_size > 0:
            h_start = random.randint(0, max(0, h - self.crop_size))
            w_start = random.randint(0, max(0, w - self.crop_size))
            rgb = rgb[h_start:h_start + self.crop_size, w_start:w_start + self.crop_size]
            depth = depth[h_start:h_start + self.crop_size, w_start:w_start + self.crop_size]

            if self.augment:
                rgb, depth = self._augment(rgb, depth)

        # Trim to multiples of 28 (patch_size=4 × window_size=7)
        h, w = depth.shape
        align = max(self.scale, 4)
        new_h = (h // align) * align
        new_w = (w // align) * align
        if new_h != h or new_w != w:
            rgb = rgb[:new_h, :new_w]
            depth = depth[:new_h, :new_w]
        h, w = depth.shape

        # Per-sample min-max normalization (same as A2GS)
        depth_min = depth.min()
        depth_max = depth.max()
        depth_range = depth_max - depth_min
        if depth_range < 1e-8:
            depth_range = 1.0
        depth_norm = (depth - depth_min) / depth_range

        # Generate LR depth from normalized depth
        lr_h, lr_w = h // self.scale, w // self.scale
        depth_tensor = torch.from_numpy(depth_norm).float()
        lr_depth = F.interpolate(
            depth_tensor.unsqueeze(0).unsqueeze(0),
            size=(lr_h, lr_w), mode="bicubic", align_corners=False
        ).squeeze(0)  # (1, lr_h, lr_w)

        # RGB edge map or raw RGB
        if self.pre_extract_edge:
            edge = compute_sobel_numpy(rgb)  # uses shared util
            rgb_input = np.stack([edge] * 3, axis=0)  # (3, H, W)
        else:
            rgb_input = np.transpose(rgb.astype(np.float32) / 255.0, (2, 0, 1))

        rgb_input = torch.from_numpy(rgb_input.astype(np.float32))
        hr_depth = depth_tensor.unsqueeze(0)  # (1, H, W)

        # Store min/max for de-normalization (×100 same as A2GS)
        dmin = torch.tensor(depth_min * 100, dtype=torch.float32)
        dmax = torch.tensor(depth_max * 100, dtype=torch.float32)

        return lr_depth, rgb_input, hr_depth, dmin, dmax
